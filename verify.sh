#!/usr/bin/env bash
# Compare a Home Manager build against chezmoi's rendering of every managed
# target on *this* machine (chezmoi only renders for the OS it runs on).
#
#   ./verify.sh [role]      role defaults to linux on Linux, darwin on macOS;
#                           the configuration used is $(id -un)@<role>
#
# Each target is reported as
#   OK         identical (byte-for-byte or via a semantic comparator)
#   EXPLAINED  differs/absent by design; reason given, see MIGRATION.md
#   MISMATCH   unexpected difference (exit status 1)
# Encrypted targets are never rendered (that would decrypt them); only their
# destination paths are checked against thom.age.secrets.
set -uo pipefail

case "$(uname -s)" in
Darwin) default_role=darwin ;;
*) default_role=linux ;;
esac
role=${1:-$default_role}

cd "$(dirname "$0")" || exit 1
export NIX_CONFIG="experimental-features = nix-command flakes"
user=$(id -un)
hm=".#homeConfigurations.\"$user@$role\""

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

echo "building $user@$role ..." >&2
nix build -o "$work/result" "$hm.activationPackage" || exit 1
hf="$work/result/home-files"
container=$(nix eval "$hm.config.thom.container")
bin="$work/result/home-path/bin"

ok=0 explained=0 mismatch=0
OK() {
	printf 'OK         %s\n' "$1"
	ok=$((ok + 1))
}
EXPLAINED() {
	printf 'EXPLAINED  %s  (%s)\n' "$1" "$2"
	explained=$((explained + 1))
}
MISMATCH() {
	printf 'MISMATCH   %s  %s\n' "$1" "${2:-}"
	mismatch=$((mismatch + 1))
}

# compare <label> <file-a> <file-b>
compare() {
	if diff -u "$2" "$3" >"$work/diff"; then
		OK "$1"
	else
		MISMATCH "$1"
		sed 's/^/           /' "$work/diff"
	fi
}

render() { chezmoi --source "$PWD" cat "$HOME/$1" >"$work/cz" 2>"$work/cz.err"; }

# --- semantic normalisers ---------------------------------------------------

git_list() {
	"$bin/git" config -f "$1" --list |
		# chezmoi pointed at ~/.gitignore/.gitattributes; HM uses git's
		# default ~/.config/git/{ignore,attributes}.
		grep -vE '^core\.(excludesfile|attributesfile)=' |
		# gh helper: bare/Homebrew path vs Nix store path.
		sed -E 's#^(credential\..*\.helper=)!?[^ ]*/?gh auth#\1gh auth#' |
		# Equivalent git booleans.
		sed -E 's/=(off|no)$/=false/; s/=(on|yes)$/=true/' |
		sort
}

tmux_seq=0
tmux_opts() {
	tmux_seq=$((tmux_seq + 1))
	local sock="verify$$-$tmux_seq"
	EDITOR=nvim TMUX_TMPDIR="$work" "$bin/tmux" -L "$sock" -f "$1" \
		new-session -d \; \
		show-options -g \; show-options -gw \; show-options -s \; \
		kill-server |
		# Session-specific / Nix-vs-Homebrew PATH, compared by hand.
		grep -vE '^(default-shell|default-command|update-environment)'
}

# Start an interactive login zsh in a scratch HOME populated from either
# chezmoi (cz) or the Home Manager build (hm), and dump its resulting state.
zsh_state() {
	local home="$work/home-$1"
	if [[ ! -d $home ]]; then
		mkdir -p "$home"
		if [[ $1 == cz ]]; then
			chezmoi --source "$PWD" archive --format=tar --exclude=encrypted,scripts 2>/dev/null \
				"$HOME/.zshrc" "$HOME/.zshenv" "$HOME/.zprofile" "$HOME/.zsh" |
				tar -xm -C "$home"
			# Written by a run_ script under chezmoi.
			mkdir -p "$home/.cache"
			cp "$hf/.cache/ls_colors" "$home/.cache/"
		else
			cp -rL "$hf/." "$home/"
			chmod -R u+w "$home"
		fi
	fi
	cat >"$work/probe.zsh" <<'PROBE'
setopt; print -- '---'; alias; print -- '---'; bindkey; print -- '---'; zstyle -L; print -- '---'
print -l ${(k)functions} | grep -v '^_' | sort
PROBE
	env -i HOME="$home" TERM=xterm-256color USER="$USER" PATH="$bin:/usr/bin:/bin" \
		"$bin/zsh" -il -c "source $work/probe.zsh" 2>&1 |
		# Added by programs.zsh's history module (safer history file locking).
		grep -vx histfcntllock
}

toml_json() { "$bin/python3" -c 'import json,sys,tomllib; print(json.dumps(tomllib.load(open(sys.argv[1],"rb")),sort_keys=True,indent=1))' "$1"; }
# Blank and null gh settings both mean "use the default".
yaml_json() { nix run --inputs-from . nixpkgs#yq-go -- -o json -P 'del(.[] | select(. == null or . == "")) | sort_keys(..)' "$1"; }
gpg_norm() { grep -vE '^\s*(#|$)' "$1" | sed -E 's/[[:space:]]+/ /g' | sort; }

# --- per-target handling ----------------------------------------------------

check() {
	local p="$1" h="$hf/$1"
	case "$p" in
	.zshrc)
		zsh_state cz >"$work/a"
		zsh_state hm >"$work/b"
		compare "$p (+ .zshenv/.zprofile: interactive login shell setopt/alias/bindkey/zstyle/functions)" "$work/a" "$work/b"
		;;
	.zshenv | .zprofile)
		if "$bin/zsh" -n "$h"; then
			EXPLAINED "$p" "generated by programs.zsh; behaviour checked with .zshrc"
		else
			MISMATCH "$p" "zsh -n failed"
		fi
		;;
	.zsh/zsh-defer/*)
		EXPLAINED "$p" "zsh-defer comes from pkgs.zsh-defer in the store"
		;;
	.gitconfig)
		render "$p"
		git_list "$work/cz" >"$work/a"
		git_list "$hf/.config/git/config" >"$work/b"
		compare "$p -> .config/git/config (git config --list)" "$work/a" "$work/b"
		;;
	.gitignore | .gitattributes)
		render "$p"
		local x=${p#.git}
		[[ $x == ignore ]] || x=attributes
		[[ $p == .gitignore ]] && x=ignore
		compare "$p -> .config/git/$x" "$work/cz" "$hf/.config/git/$x"
		;;
	.tmux.conf)
		render "$p"
		tmux_opts "$work/cz" >"$work/a"
		tmux_opts "$hf/.config/tmux/tmux.conf" >"$work/b"
		compare "$p -> .config/tmux/tmux.conf (tmux show-options)" "$work/a" "$work/b"
		;;
	.config/starship.toml)
		render "$p"
		toml_json "$work/cz" >"$work/a"
		toml_json "$h" >"$work/b"
		compare "$p (parsed TOML)" "$work/a" "$work/b"
		;;
	.config/gh/config.yml)
		render "$p"
		yaml_json "$work/cz" >"$work/a"
		yaml_json "$h" >"$work/b"
		compare "$p (parsed YAML)" "$work/a" "$work/b"
		;;
	.gnupg/gpg.conf)
		render "$p"
		gpg_norm "$work/cz" >"$work/a"
		gpg_norm "$h" >"$work/b"
		compare "$p (options, comments stripped)" "$work/a" "$work/b"
		;;
	.config/ghostty/*)
		if [[ $role == darwin ]]; then
			render "$p"
			if [[ $p == */config.ghostty ]]; then
				sed -E '/^\s*(#|$)/d; s/\s*=\s*/ = /' "$work/cz" | sort >"$work/a"
				sed -E '/^\s*(#|$)/d; s/\s*=\s*/ = /' "$hf/.config/ghostty/config" | sort >"$work/b"
				compare "$p -> .config/ghostty/config" "$work/a" "$work/b"
			else
				compare "$p" "$work/cz" "$h"
			fi
		else
			EXPLAINED "$p" "Ghostty config is darwin-only now (no Linux desktops)"
		fi
		;;
	.claude.json | .claude/settings.json)
		# modify_ scripts: run both merges on an empty file.
		local src filter
		if [[ $p == .claude.json ]]; then
			src=modify_private_dot_claude.json.tmpl filter=jsonMerge
		else
			src=dot_claude/modify_private_settings.json.tmpl filter=settingsMerge
		fi
		chezmoi --source "$PWD" execute-template <"$src" >"$work/cz.sh"
		# shellcheck disable=SC2016 # jq variables
		echo '{}' | bash "$work/cz.sh" |
			"$bin/jq" -S --argjson c "$container" '
				if .sandbox then
					# HM denies both the chezmoi-era and the new identity path.
					.sandbox.credentials.files |= (.[0:3] + [{path: "~/.config/age/keys.txt", mode: "deny"}] + .[3:])
					# chezmoi detected containers at runtime; HM sets it per role.
					| .sandbox.enableWeakerNestedSandbox = $c
				else . end
			' >"$work/a"
		echo '{}' | "$(nix build --no-link --print-out-paths "$hm.config.thom.claude.$filter")" |
			"$bin/jq" -S '
				if .sandbox.filesystem.allowRead then .sandbox.filesystem.allowRead -= ["~/.config/git"] else . end
				# The checkout moved from the chezmoi source dir.
				| if .sandbox.filesystem then .sandbox.filesystem |= with_entries(
					if .key == "allowRead" or .key == "allowWrite"
					then .value |= map(if . == "~/.config/home-manager" then "~/.local/share/chezmoi" else . end)
					else . end) else . end
			' >"$work/b"
		compare "$p (jq merge on {}; age key path, ~/.config/git read, checkout path, container flag normalised)" "$work/a" "$work/b"
		;;
	*)
		if [[ ! -e $h ]]; then
			MISMATCH "$p" "not produced by Home Manager"
			return
		fi
		render "$p"
		compare "$p" "$work/cz" "$h"
		;;
	esac
}

echo "== plain targets"
while IFS= read -r p; do
	check "$p"
done < <(chezmoi --source "$PWD" managed --include=files --exclude=encrypted)

echo "== encrypted targets (paths only)"
nix eval --json "$hm.config.thom.age.secrets" --apply 'builtins.mapAttrs (_: s: s.target)' |
	"$bin/jq" -r '.[]' | sort >"$work/hm-secrets"
while IFS= read -r p; do
	want=$p
	# ~/.ssh/config is split: generic part native, host blocks encrypted and
	# included. Checked once with ssh -G against the decrypted original.
	if [[ $p == .ssh/config ]]; then
		want=.ssh/config.private
		grep -qx 'Include config.private' "$hf/.ssh/config" ||
			MISMATCH "$p" ".ssh/config does not include config.private"
	fi
	if grep -qxF "$want" "$work/hm-secrets"; then
		if [[ $want == "$p" ]]; then OK "$p (secret)"; else EXPLAINED "$p" "split: generic part in programs.ssh, host blocks decrypted to $want and included"; fi
	else
		MISMATCH "$p" "no thom.age.secrets entry"
	fi
done < <(chezmoi --source "$PWD" managed --include=encrypted --exclude=dirs)

# secrets/ssh_config_private.age is a new ciphertext (host blocks only), so
# it has no chezmoi counterpart.
echo "== ciphertexts (byte compare with the chezmoi sources; nothing decrypted)"
while IFS='|' read -r new old; do
	if cmp -s "secrets/$new" "$old"; then
		OK "secrets/$new"
	else
		MISMATCH "secrets/$new" "differs from $old; re-copy it"
	fi
done <<'LIST'
halloy_config.toml.age|dot_config/exact_halloy/encrypted_config.toml.age
halloy_theme_catppucin_light.toml.age|dot_config/exact_halloy/exact_private_themes/encrypted_catppucin light.toml.age
senpai.scfg.age|dot_config/exact_senpai/encrypted_private_senpai.scfg.age
runitor_hc_key.age|dot_config/runitor/encrypted_hc_key.age
LIST

echo
echo "ok=$ok explained=$explained mismatch=$mismatch"
[[ $mismatch -eq 0 ]]
